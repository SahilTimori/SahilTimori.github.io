function render(list = products) {
  const el = document.getElementById("products");
  if (!list.length) {
    el.innerHTML = '<p style="grid-column:1/-1;color:#687383">No matching picks yet.</p>';
    return;
  }
  el.innerHTML = list.map(p => `
    <article class="product">
      <div class="product-img">${p.emoji}</div>
      <h3>${p.name}</h3>
      <p style="font-size:11px;line-height:1.5;color:#687383;min-height:70px">${p.description}</p>
      <div class="deal">${p.type}</div>
      <a class="amazon-btn" href="${p.url}" target="_blank" rel="nofollow sponsored noopener">a &nbsp; Check on Amazon</a>
    </article>
  `).join("");
}

function filterCategory(cat) {
  render(products.filter(p => p.cat === cat));
  document.getElementById("deals").scrollIntoView({behavior:"smooth"});
}
function showAll() {
  render();
  document.getElementById("deals").scrollIntoView({behavior:"smooth"});
}
function searchProducts() {
  const q = document.getElementById("searchInput").value.toLowerCase();
  render(products.filter(p => (p.name + " " + p.cat + " " + p.description).toLowerCase().includes(q)));
  document.getElementById("deals").scrollIntoView({behavior:"smooth"});
}
function toggleMenu() {
  const nav = document.getElementById("navLinks");
  nav.style.display = nav.style.display === "flex" ? "none" : "flex";
}
function subscribe(e) {
  e.preventDefault();
  const toast = document.getElementById("toast");
  toast.textContent = "Thanks! Newsletter signup is ready to connect to your email service.";
  toast.style.display = "block";
  setTimeout(() => toast.style.display = "none", 3500);
  e.target.reset();
}
document.getElementById("searchInput").addEventListener("keydown", e => {
  if (e.key === "Enter") searchProducts();
});
